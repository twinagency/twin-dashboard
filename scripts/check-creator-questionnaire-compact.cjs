const assert = require('node:assert/strict');
const { resolve, basename } = require('node:path');
const { build } = require('esbuild');
const { JSDOM } = require('jsdom');
const { rmSync } = require('node:fs');
(async () => {
 const stem=resolve('node_modules/.cache/compact-onboarding-'+basename(process.cwd()));
 await build({entryPoints:{Wizard:'components/CreatorQuestionnaireWizard.tsx',Draft:'lib/creator-questionnaire-draft.ts',Compact:'lib/creator-questionnaire-compact.ts',Questions:'lib/creator-questionnaire.ts'},outdir:stem,bundle:true,platform:'node',format:'cjs',packages:'external',jsx:'automatic',define:{'window.location.assign':'globalThis.__compactNavigate'}});
 const {COMPACT_QUESTIONNAIRE_PAGES:pages,COMPACT_QUESTIONNAIRE_ALIASES:aliases}=require(stem+'/Compact.js');
 const {CREATOR_QUESTIONNAIRE:questions}=require(stem+'/Questions.js');
 const draft=require(stem+'/Draft.js');
 assert.equal(pages.length,5);
 const ids=pages.flatMap(p=>draft.questionnairePageQuestions(p).map(q=>q.id));
 assert.deepEqual([...ids].sort(),questions.map(q=>q.id).sort(),'every existing field appears exactly once');
 const expanded=pages.flatMap(p=>p.sections.filter(g=>!g.optionalDetails).flatMap(g=>g.questions.map(q=>q.id)));
 for(const id of draft.CREATOR_QUESTIONNAIRE_REQUIRED_IDS)assert.ok(expanded.includes(id),'required fields never hidden');
 assert.equal(draft.creatorQuestionnairePage(null).slug,'personal-contact','other brands retain legacy flow');
 assert.equal(draft.creatorQuestionnairePage(null,true).slug,pages[0].slug);
 for(const [old,next]of Object.entries(aliases))assert.equal(draft.creatorQuestionnairePage(old,true).slug,next);
 for(const page of pages){
  const answers=Object.fromEntries(draft.questionnairePageQuestions(page).map(q=>[q.id,q.options?.[0]||'Existing answer']));
  assert.equal(draft.creatorQuestionnairePage(page.slug).slug,page.slug,'draft endpoint recognises new sections');
  assert.deepEqual(draft.parseQuestionnairePagePatch(page,answers),answers);
 }
 const dom=new JSDOM('<div id="root"></div>',{url:'https://creator.example/creator/onboarding?step=questionnaire'});
 for(const name of ['window','document','HTMLElement','Event','MouseEvent','FormData'])global[name]=dom.window[name];
 Object.defineProperty(global,'navigator',{value:dom.window.navigator,configurable:true});global.IS_REACT_ACT_ENVIRONMENT=true;
 const navigations=[];global.__compactNavigate=url=>navigations.push(url);
 const React=require('react'),{act}=React,{createRoot}=require('react-dom/client');
 const Wizard=require(stem+'/Wizard.js').default;
 let root=createRoot(document.getElementById('root'));
 const render=async(page,answers={},optional=true)=>act(async()=>root.render(React.createElement(Wizard,{page,initialAnswers:answers,initialRevision:'old-revision',optional})));
 const reset=async()=>{await act(async()=>root.unmount());root=createRoot(document.getElementById('root'));};
 const click=async(label)=>act(async()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===label);assert.ok(b,label);b.click();});
 let payload, fail=false;
 global.fetch=async(url,init)=>{payload=JSON.parse(init.body);return{ok:!fail,status:fail?503:200,json:async()=>fail?{}:{revision:'new-revision'}};};
 await render(pages[0],{full_name:'Saved name',pets:'Saved pet'});
 assert.match(document.body.textContent,/Section 1 of 5/);
 assert.equal(document.querySelectorAll('[data-questionnaire-navigation] button').length,2);
 assert.ok([...document.querySelectorAll('details')].every(el=>!el.open));
 assert.equal(new FormData(document.querySelector('form')).get('pets'),'Saved pet','collapsed details retain saved values');
 const input=document.querySelector('[name="full_name"]');
 await act(async()=>{input.value='Updated name';input.dispatchEvent(new Event('input',{bubbles:true}));});
 fail=true;await click('Continue');
 assert.equal(navigations.length,0,'failed autosave prevents losing answers');
 assert.equal(input.value,'Updated name');
 fail=false;await click('Continue');
 assert.equal(payload.answers.pets,'Saved pet','saving visible questions must not erase hidden answers');
 assert.equal(payload.answers.full_name,'Updated name');
 assert.equal(navigations.pop(),'/creator/onboarding?step=questionnaire&section=quick-style');
 await reset();await render(pages[3],{},false);
 assert.equal(document.querySelector('[name="boundaries"]').required,true);
 assert.equal(document.querySelector('[name="boundaries"]').closest('details'),null);
 await reset();await render(pages[4]);
 global.fetch=async()=>({ok:true,status:200,url:'https://creator.example/creator/onboarding?status=questionnaire_saved'});
 await click('Continue to content');assert.equal(navigations.pop(),'/creator/onboarding?step=content');
 await reset();await render(pages[0]);
 global.fetch=async()=>{throw Error('blank optional skip must not submit');};
 await click('Skip questions');assert.equal(navigations.pop(),'/creator/onboarding?step=content');
 await act(async()=>root.unmount());rmSync(stem,{recursive:true,force:true});
 console.log('Compact onboarding passed: 5 sections, all '+ids.length+' answer IDs preserved, legacy links, required fields visible, hidden saved answers retained, save failure/retry, next/finish/skip navigation.');
})().catch(error=>{console.error(error);process.exitCode=1;});
