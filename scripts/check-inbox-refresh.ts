import assert from "node:assert/strict";
import {initialSelectionState,requestConversations,applyConversations,applyConversationRefresh,requestMoreConversations,selectConversation,beginScope} from "../lib/onlyfans-preview/selection";
const row=(id:string)=>({conversationId:id,accountId:"acc-a"}) as any;
const page=(ids:string[],nextCursor:string|null)=>({status:"ready",data:{accountId:"acc-a",items:ids.map(row),nextCursor}}) as any;
let state=initialSelectionState();state.selectedAccountId="acc-a";
let initial=requestConversations(state,"acc-a");state=applyConversations(initial.state,"acc-a",initial.generation,initial.seq,page(["acc-a:1","acc-a:2"],"tail")).state;
state=selectConversation(state,"acc-a","acc-a:2");
const pending=requestConversations(state,"acc-a",{background:true});
assert.equal(pending.state.byAccount["acc-a"].conversations.status,"ready","background refresh must retain visible rows");
const refreshed=applyConversationRefresh(pending.state,"acc-a",pending.generation,pending.seq,page(["acc-a:3","acc-a:1"],"new-head"));
assert(refreshed.applied);
const list=refreshed.state.byAccount["acc-a"].conversations as any;
assert.deepEqual(list.data.items.map((r:any)=>r.conversationId),["acc-a:3","acc-a:1","acc-a:2"]);
assert.equal(refreshed.state.byAccount["acc-a"].selectedConversationId,"acc-a:2");
assert.equal(list.data.nextCursor,"tail");
assert(!applyConversationRefresh(beginScope(pending.state),"acc-a",pending.generation,pending.seq,page(["foreign"],null)).applied);
const paged=requestMoreConversations(pending.state,"acc-a");
assert(!applyConversationRefresh(paged.state,"acc-a",pending.generation,pending.seq,page(["stale"],null)).applied);
const empty=applyConversationRefresh(pending.state,"acc-a",pending.generation,pending.seq,page([],null));
assert.equal(empty.state.byAccount["acc-a"].selectedConversationId,null,"proved empty list must clear stale controls");
console.log("Inbox refresh PASS: background rows, new fan, stable selected thread, loaded-page cursor, stale generation/sequence and empty-list recovery.");
