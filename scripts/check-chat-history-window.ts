import assert from "node:assert/strict";
import { historyWindowQuery, historyCursor, parseHistoryCursor } from "../lib/chat-history-window";
const now = Date.parse("2026-10-12T03:00:00Z");
assert.equal(parseHistoryCursor("junk"), null);
assert.equal(parseHistoryCursor("2026-10-10T01:00:00Z|1),clone_id.neq.x"), null);
const exact = historyCursor({ created_at: "2026-10-10T01:00:00.123456+00:00", id: "9007199254740993" });
assert.equal(exact, "2026-10-10T01:00:00.123456Z|9007199254740993");
assert.equal(parseHistoryCursor(exact)?.at, "2026-10-10T01:00:00.123456Z");
const calls: any[] = []; const query: any = {};
for (const name of ["gte", "lte", "or", "order", "limit"]) query[name] = (...args: any[]) => { calls.push([name, ...args]); return query; };
historyWindowQuery(query, { before: exact, now });
assert.deepEqual(calls[0], ["gte", "created_at", "2026-07-14T03:00:00.000Z"]);
assert.deepEqual(calls[1], ["lte", "created_at", "2026-10-12T03:00:00.000Z"]);
assert.deepEqual(calls[2], ["or", "created_at.lt.2026-10-10T01:00:00.123456Z,and(created_at.eq.2026-10-10T01:00:00.123456Z,id.lt.9007199254740993)"]);
assert.deepEqual(calls.slice(-3), [["order", "created_at", { ascending: false }], ["order", "id", { ascending: false }], ["limit", 101]]);
calls.length = 0; historyWindowQuery(query, { after: exact, now }); assert.equal(calls[3][2].ascending, true); assert(calls[2][1].includes("id.gt."));
calls.length = 0; historyWindowQuery(query, { before: "malformed", now }); assert(!calls.some(c => c[0] === "or"));
console.log("90-day V1 history: cutoff, stable paging, reverse paging, microsecond/bigint cursors and malformed-input rejection passed.");
